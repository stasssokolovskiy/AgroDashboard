--- BACKEND

CREATE USER :"BACKEND_DB_USER" WITH PASSWORD :'BACKEND_DB_PASSWORD';
ALTER DATABASE :"POSTGRES_DB" OWNER TO :"BACKEND_DB_USER";
GRANT ALL PRIVILEGES ON SCHEMA public TO :"BACKEND_DB_USER";

--- FRONTEND

CREATE USER :"FRONTEND_DB_USER" WITH PASSWORD :'FRONTEND_DB_PASSWORD' CONNECTION LIMIT 20;

ALTER ROLE :"FRONTEND_DB_USER" SET statement_timeout = '10s';
ALTER ROLE :"FRONTEND_DB_USER" SET idle_in_transaction_session_timeout = '30s';
ALTER ROLE :"FRONTEND_DB_USER" SET work_mem = '16MB';

GRANT CONNECT ON DATABASE :"POSTGRES_DB" TO :"FRONTEND_DB_USER";
GRANT USAGE ON SCHEMA public TO :"FRONTEND_DB_USER";
GRANT SELECT ON ALL TABLES IN SCHEMA public TO :"FRONTEND_DB_USER";

ALTER DEFAULT PRIVILEGES FOR ROLE :"BACKEND_DB_USER" IN SCHEMA public
GRANT SELECT ON TABLES TO :"FRONTEND_DB_USER";